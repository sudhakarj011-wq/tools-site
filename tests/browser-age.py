# Browser test for the age page. Usage: python3 tests/browser-fd.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8780', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8780/tools/age-calculator.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        flat = lambda: txt().replace('\n', '')
        def dates(d, a):
            pg.fill('#dob', d); pg.fill('#ason', a)
        today = pg.evaluate("(()=>{const t=new Date(),p=n=>(n<10?'0':'')+n;return t.getFullYear()+'-'+p(t.getMonth()+1)+'-'+p(t.getDate())})()")
        check('"Age as on" starts with today', pg.input_value('#ason') == today, pg.input_value('#ason'))
        check('empty date of birth: no result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        dates('1995-08-15', '2026-10-20')
        check('15 Aug 1995 as on 20 Oct 2026: 31 years, 2 months, 5 days', '31 years, 2 months, 5 days' in txt(), txt()[:80])
        check('born on Tuesday', 'Born onTuesday' in flat(), flat()[:120])
        check('next birthday 15 August 2027 (Sunday), in 299 days', '15 August 2027 (Sunday), in 299 days' in txt(), txt()[:200])
        pg.click('.sched summary')
        check('totals: 374 months, 1,627 weeks 0 days, 11,389 days', all(x in pg.inner_text('.sched') for x in ['374', '1,627 weeks, 0 days', '11,389']), pg.inner_text('.sched'))
        dates('1976-07-01', '2026-07-01')
        check('birthday today: 50 years, Today! You turn 50', '50 years, 0 months, 0 days' in txt() and 'Today! You turn 50' in txt(), txt()[:160])
        dates('1976-07-01', '2026-06-30')
        check('day before birthday: 49 years, 11 months, 29 days; in 1 day', '49 years, 11 months, 29 days' in txt() and 'in 1 day' in txt() and 'in 1 days' not in txt(), txt()[:160])
        dates('1990-01-31', '2023-03-01')
        check('month-end: 31 Jan 1990 as on 1 Mar 2023 = 33 years, 1 month, 1 day', '33 years, 1 month, 1 day' in txt(), txt()[:80])
        dates('2000-02-29', '2026-03-01')
        check('leap day: 26 years, 0 months, 1 day; next birthday 28 February 2027', '26 years, 0 months, 1 day' in txt() and '28 February 2027' in txt(), txt()[:160])
        dates('2026-10-20', '2026-10-20')
        check('born today: 0 years, 0 months, 0 days', '0 years, 0 months, 0 days' in txt(), txt()[:80])
        dates('2026-10-21', '2026-10-20')
        check('birth date after "as on" date shows hint', pg.is_visible('#hint') and not pg.is_visible('#out') and 'on or before' in pg.inner_text('#hint'))
        dates('1899-12-31', '2026-10-20')
        check('year before 1900 shows valid-date hint', pg.is_visible('#hint') and 'valid date' in pg.inner_text('#hint'))
        dates('2001-03-10', '2030-01-01')
        check('future "as on" date works: 28 years, 9 months, 22 days', '28 years, 9 months, 22 days' in txt(), txt()[:80])
        pg.fill('#ason', '')
        check('clearing "as on" falls back to today', pg.input_value('#ason') == today)
        pg.fill('#ason', '2030-01-01'); pg.click('#today')
        check('"Use today" resets the as-on date', pg.input_value('#ason') == today)
        dates('1995-08-15', '2026-10-20')
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result summary on clipboard', clip == 'Born 15 August 1995, age on 20 October 2026: 31 years, 2 months, 5 days | Next birthday: 15 August 2027', clip)
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle'); q.fill('#dob', '1995-08-15')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget .btn')].every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
