# Browser test for the discount page. Usage: python3 tests/browser-fd.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8781', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8781/tools/discount-calculator.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        flat = lambda: txt().replace('\n', '')
        mode = lambda v: pg.click(f'#mode button[data-v="{v}"]')
        def f(**kw):
            for k, v in kw.items(): pg.fill('#' + k, str(v))
        check('default: 2,500, 20% + 10% -> you pay ₹1,800.00, save ₹700.00, total 28%', 'You pay₹1,800.00' in flat() and 'You save₹700.00' in flat() and 'Total discount28%' in flat(), flat()[:160])
        check('sale mode shows discount boxes, hides sale price box', pg.is_visible('#d1') and pg.is_visible('#d2') and not pg.is_visible('#s'))
        check('shows the price after the first discount ₹2,000.00', 'After first discount₹2,000.00' in flat())
        f(p=1999, d1=15, d2=''); check('1,999 with 15% -> ₹1,699.15, save ₹299.85', '₹1,699.15' in txt() and '₹299.85' in txt(), txt()[:80])
        check('no extra discount: "After first discount" row hidden', 'After first discount' not in txt())
        f(p=4999, d1=30, d2=20); check('4,999 with 30% + 20% -> ₹2,799.44, total 44%', '₹2,799.44' in txt() and '44%' in txt(), txt()[:100])
        f(p=999, d1=50, d2=0); check('999 with 50% -> ₹499.50', '₹499.50' in txt())
        f(p=1000, d1=100, d2=''); check('100% off -> you pay ₹0.00', 'You pay₹0.00' in flat())
        f(d1=101); check('101% shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        f(d1=10, d2=150); check('extra discount 150% shows hint', pg.is_visible('#hint'))
        f(d2=''); f(p=0); check('price 0 shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        f(p=''); check('empty price hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        f(p=2500, d1=''); check('empty discount hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        f(p=1000, d1=-5); check('negative discount shows hint', pg.is_visible('#hint'))
        f(p=2500, d1=20, d2=10)
        pg.click('.sched summary')
        check('working has 3 steps with extra discount', pg.locator('.sched tbody tr').count() == 3)
        check('working step 2 shows the extra discount ₹1,800.00', '₹1,800.00' in pg.locator('.sched tbody tr').nth(1).inner_text())
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result in sale mode', clip == 'Price ₹2,500.00, 20% + 10% off | You pay ₹1,800.00 | You save ₹700.00 (28%)', clip)
        mode('pct')
        check('pct mode shows sale price box, hides discount boxes', pg.is_visible('#s') and not pg.is_visible('#d1') and not pg.is_visible('#d2'))
        check('only one mode button pressed', pg.locator('#mode button[aria-pressed="true"]').count() == 1)
        check('pct defaults 2,000 -> 1,500 = 25%, save ₹500.00', 'Discount25%' in flat() and 'You save₹500.00' in flat(), flat()[:120])
        f(p=1299, s=999); check('1,299 -> 999 = 23.0947%', '23.0947%' in txt(), txt()[:60])
        f(p=500, s=500); check('500 -> 500 = 0%', 'Discount0%' in flat())
        f(p=999, s=0); check('999 -> 0 = 100%', 'Discount100%' in flat())
        f(p=100, s=150); check('sale above original shows hint', pg.is_visible('#hint') and not pg.is_visible('#out') and 'between 0 and the original' in pg.inner_text('#hint'))
        f(p=100, s=''); check('empty sale price hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        f(p=4999, s=3499); check('4,999 -> 3,499 = 30.006%', '30.006%' in txt())
        pg.click('.sched summary')
        check('pct working has 2 steps', pg.locator('.sched tbody tr').count() == 2)
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result in pct mode', clip == 'Original ₹4,999.00, sale ₹3,499.00 | Discount 30.006% | You save ₹1,500.00', clip)
        mode('sale')
        check('back to sale mode restores defaults and result', pg.input_value('#p') == '2500' and 'You pay₹1,800.00' in flat())
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget .seg button, .widget .btn')].filter(e=>e.offsetParent!==null).every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
