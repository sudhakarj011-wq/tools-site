# Browser test for the SIP page. Usage: python3 tests/browser-sip.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8772', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8772/tools/sip-calculator.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        check('default: expected value ₹11,61,695', '₹11,61,695' in txt(), txt()[:80])
        check('default: invested ₹6,00,000 and returns ₹5,61,695', '₹6,00,000' in txt() and '₹5,61,695' in txt())
        check('amount words: 5 Thousand per month', pg.inner_text('#amount-words') == '= 5 Thousand per month')
        pg.fill('#amount', '10000'); pg.fill('#rate', '12'); pg.fill('#tenure', '15')
        check('10,000 at 12% for 15y -> 50,45,760', '₹50,45,760' in txt(), txt()[:60])
        pg.fill('#amount', '25000'); pg.fill('#tenure', '20')
        check('25,000 at 12% for 20y -> 2,49,78,698', '₹2,49,78,698' in txt(), txt()[:60])
        pg.fill('#amount', '5000'); pg.fill('#tenure', '10')
        pg.eval_on_selector('#amount-r', "e=>{e.value=10000;e.dispatchEvent(new Event('input',{bubbles:true}))}")
        check('amount slider updates number box', pg.input_value('#amount') == '10000')
        pg.eval_on_selector('#tenure-r', "e=>{e.value=20;e.dispatchEvent(new Event('input',{bubbles:true}))}")
        check('tenure slider updates number box and result', pg.input_value('#tenure') == '20' and '₹' in txt())
        pg.fill('#amount', '300000')
        check('value above slider max still calculates', pg.is_visible('#out'))
        pg.fill('#amount', '5000'); pg.fill('#tenure', '10')
        pg.fill('#rate', '0')
        check('0% return: value = invested = 6,00,000', txt().count('₹6,00,000') >= 2, txt()[:80])
        pg.fill('#rate', '75')
        check('rate 75% shows hint, hides result', pg.is_visible('#hint') and not pg.is_visible('#out'))
        pg.fill('#rate', '')
        check('empty rate hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        pg.fill('#rate', '12'); pg.fill('#tenure', '2.5')
        check('2.5 years accepted (30 months)', pg.is_visible('#out') and '₹1,50,000' in txt(), txt()[:80])
        pg.fill('#tenure', '2.55')
        check('2.55 years rejected with hint', pg.is_visible('#hint'))
        pg.fill('#tenure', '51')
        check('51 years rejected', pg.is_visible('#hint'))
        pg.fill('#tenure', '50')
        check('50 years accepted', pg.is_visible('#out'))
        pg.fill('#amount', '0')
        check('amount 0 rejected', pg.is_visible('#hint'))
        pg.fill('#amount', '5000'); pg.fill('#tenure', '10')
        pg.click('.sched summary')
        rows = pg.locator('.sched tbody tr').count()
        check('schedule has 10 rows', rows == 10, str(rows))
        check('last schedule row value is ₹11,61,695', '₹11,61,695' in pg.locator('.sched tbody tr').last.inner_text())
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result puts summary on clipboard', 'Expected value ₹11,61,695' in clip and 'SIP' in clip, clip)
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget .btn')].every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
