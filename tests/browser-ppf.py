# Browser test for the PPF page. Usage: python3 tests/browser-fd.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8775', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8775/tools/ppf-calculator.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        mode = lambda v: pg.click(f'#mode button[data-v="{v}"]')
        check('default: maturity ₹40,68,209, interest ₹18,18,209', '₹40,68,209' in txt() and '₹18,18,209' in txt(), txt()[:80])
        check('default mode is Once a year', pg.get_attribute('#mode button[data-v="yearly"]', 'aria-pressed') == 'true')
        check('amount words: = 1.5 Lakh', pg.inner_text('#amount-words') == '= 1.5 Lakh')
        check('default rate is 7.1 and life is 15', pg.input_value('#rate') == '7.1' and pg.input_value('#tenure') == '15')
        mode('monthly')
        check('switch to monthly: 1.5L/year -> 12,500/month', pg.input_value('#amount') == '12500', pg.input_value('#amount'))
        check('monthly label', 'month' in pg.inner_text('#amount-l'))
        check('monthly 12,500 -> ₹39,44,599', '₹39,44,599' in txt(), txt()[:60])
        pg.fill('#amount', '12501')
        check('12,501 a month rejected (over 1.5L a year)', pg.is_visible('#hint') and not pg.is_visible('#out'))
        pg.fill('#amount', '5000'); pg.fill('#tenure', '30')
        check('5,000/month, 30y -> ₹59,92,578', '₹59,92,578' in txt(), txt()[:60])
        mode('yearly')
        check('back to yearly: 5,000/month -> 60,000/year', pg.input_value('#amount') == '60000', pg.input_value('#amount'))
        check('only one mode button pressed', pg.locator('#mode button[aria-pressed="true"]').count() == 1)
        pg.fill('#amount', '100000'); pg.fill('#rate', '8'); pg.fill('#tenure', '20')
        check('1L/year, 8%, 20y -> ₹49,42,292', '₹49,42,292' in txt(), txt()[:60])
        pg.eval_on_selector('#tenure-r', "e=>{e.value=25;e.dispatchEvent(new Event('input',{bubbles:true}))}")
        check('life slider updates box', pg.input_value('#tenure') == '25')
        pg.fill('#amount', '150000'); pg.fill('#rate', '7.1'); pg.fill('#tenure', '25')
        check('1.5L/year, 25y -> ₹1,03,08,015', '₹1,03,08,015' in txt(), txt()[:60])
        pg.fill('#rate', '0'); pg.fill('#tenure', '15')
        check('0% rate: maturity = invested ₹22,50,000', txt().count('₹22,50,000') >= 2, txt()[:70])
        pg.fill('#rate', '16')
        check('rate 16% shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        pg.fill('#rate', '')
        check('empty rate hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        pg.fill('#rate', '7.1'); pg.fill('#tenure', '17')
        check('17 years rejected (blocks of 5)', pg.is_visible('#hint'))
        pg.fill('#tenure', '10')
        check('10 years rejected (min 15)', pg.is_visible('#hint'))
        pg.fill('#tenure', '55')
        check('55 years rejected (max 50)', pg.is_visible('#hint'))
        pg.fill('#tenure', '50')
        check('50 years accepted', pg.is_visible('#out'))
        pg.fill('#amount', '499')
        check('499 a year rejected', pg.is_visible('#hint'))
        pg.fill('#amount', '150001')
        check('1,50,001 a year rejected', pg.is_visible('#hint'))
        pg.fill('#amount', '150000'); pg.fill('#tenure', '15')
        pg.click('.sched summary')
        rows = pg.locator('.sched tbody tr').count()
        check('schedule has 15 rows', rows == 15, str(rows))
        check('first schedule row balance ₹1,60,650', '₹1,60,650' in pg.locator('.sched tbody tr').first.inner_text())
        check('last schedule row is ₹40,68,209', '₹40,68,209' in pg.locator('.sched tbody tr').last.inner_text())
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result summary on clipboard', 'Maturity value ₹40,68,209' in clip and 'per year' in clip, clip)
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget .seg button, .widget .btn')].every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
