# Browser test for the simple interest page. Usage: python3 tests/browser-fd.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8778', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8778/tools/simple-interest.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        unit = lambda v: pg.click(f'#unit button[data-v="{v}"]')
        flat = lambda: txt().replace('\n', '')
        check('default 1L, 8%, 3y: interest ₹24,000.00, total ₹1,24,000.00', '₹24,000.00' in txt() and '₹1,24,000.00' in txt(), txt()[:90])
        check('default: interest each year ₹8,000.00, time 3', 'Interest each year₹8,000.00' in flat() and 'Time in years3' in flat(), flat()[:200])
        check('amount words: = 1 Lakh', pg.inner_text('#amount-words') == '= 1 Lakh')
        pg.fill('#amount', '50000'); pg.fill('#rate', '8'); pg.fill('#tenure', '3')
        check('50k, 8%, 3y -> ₹12,000.00, total ₹62,000.00', '₹12,000.00' in txt() and '₹62,000.00' in txt())
        pg.fill('#amount', '100000'); pg.fill('#rate', '7.5'); pg.fill('#tenure', '2.5')
        check('decimal time 2.5y -> ₹18,750.00', '₹18,750.00' in txt(), txt()[:60])
        unit('months')
        check('unit to months converts 2.5 years -> 30', pg.input_value('#tenure') == '30', pg.input_value('#tenure'))
        check('same interest after unit switch', '₹18,750.00' in txt())
        check('label says months', 'months' in pg.inner_text('#tenure-l'))
        pg.fill('#amount', '25000'); pg.fill('#rate', '12'); pg.fill('#tenure', '18')
        check('25k, 12%, 18 months -> ₹4,500.00, time 1.5', '₹4,500.00' in txt() and 'Time in years1.5' in flat(), flat()[:200])
        unit('days')
        check('unit to days converts 18 months -> 548', pg.input_value('#tenure') == '548', pg.input_value('#tenure'))
        pg.fill('#amount', '80000'); pg.fill('#rate', '9'); pg.fill('#tenure', '100')
        check('80k, 9%, 100 days -> ₹1,972.60', '₹1,972.60' in txt() and '₹81,972.60' in txt(), txt()[:80])
        pg.fill('#tenure', '365'); pg.fill('#amount', '100000'); pg.fill('#rate', '8')
        check('365 days = 1 year: ₹8,000.00', '₹8,000.00' in txt() and 'Time in years1' in flat())
        unit('years')
        check('days back to years: 365 -> 1', pg.input_value('#tenure') == '1', pg.input_value('#tenure'))
        check('only one unit button pressed', pg.locator('#unit button[aria-pressed="true"]').count() == 1)
        pg.fill('#tenure', '3')
        pg.eval_on_selector('#amount-r', "e=>{e.value=200000;e.dispatchEvent(new Event('input',{bubbles:true}))}")
        check('amount slider updates box and result (2L, 8%, 3y -> ₹48,000.00)', pg.input_value('#amount') == '200000' and '₹48,000.00' in txt(), txt()[:60])
        pg.eval_on_selector('#tenure-r', "e=>{e.value=10;e.dispatchEvent(new Event('input',{bubbles:true}))}")
        check('time slider updates box (10y -> ₹1,60,000.00)', pg.input_value('#tenure') == '10' and '₹1,60,000.00' in txt(), txt()[:60])
        pg.fill('#amount', '30000000'); pg.fill('#tenure', '3')
        check('amount above slider max still calculates', pg.is_visible('#out'))
        pg.fill('#amount', '100000'); pg.fill('#rate', '0')
        check('0% rate: interest ₹0.00', 'Simple interest₹0.00' in flat(), flat()[:60])
        pg.fill('#rate', '101')
        check('rate 101% shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        pg.fill('#rate', '')
        check('empty rate hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        pg.fill('#rate', '8'); pg.fill('#tenure', '101')
        check('101 years rejected', pg.is_visible('#hint'))
        pg.fill('#tenure', '0')
        check('time 0 rejected', pg.is_visible('#hint'))
        pg.fill('#tenure', '-2')
        check('negative time rejected', pg.is_visible('#hint'))
        pg.fill('#tenure', '100')
        check('100 years accepted', pg.is_visible('#out'))
        pg.fill('#tenure', '2.5')
        pg.click('.sched summary')
        rows = pg.locator('.sched tbody tr').count()
        check('schedule has 3 rows (2 whole years + part year)', rows == 3, str(rows))
        check('part-year row is labelled and shows ₹20,000.00', '(part)' in pg.locator('.sched tbody tr').last.inner_text() and '₹20,000.00' in pg.locator('.sched tbody tr').last.inner_text(), pg.locator('.sched tbody tr').last.inner_text())
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result summary on clipboard', 'Interest ₹20,000.00' in clip and 'years' in clip, clip)
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget .seg button, .widget .btn')].every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
