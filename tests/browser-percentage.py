# Browser test for the percentage page. Usage: python3 tests/browser-fd.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8779', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8779/tools/percentage-calculator.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        flat = lambda: txt().replace('\n', '')
        mode = lambda v: pg.select_option('#mode', v)
        def ab(a, b): pg.fill('#a', str(a)); pg.fill('#b', str(b))
        check('default: 15% of 2,000 is 300', '15% of 2,000 is' in txt() and '300' in txt(), txt()[:80])
        check('default labels', pg.inner_text('#la') == 'Percentage (%)' and pg.inner_text('#lb') == 'Of this number')
        ab(7.5, 240); check('7.5% of 240 -> 18', '7.5% of 240 is' in txt() and '\n18\n' in '\n' + txt() + '\n', txt()[:80])
        mode('is')
        check('mode is: defaults 45 / 180, labels change', pg.input_value('#a') == '45' and pg.input_value('#b') == '180' and pg.inner_text('#la') == 'This number (A)')
        check('45 is 25% of 180', '25%' in txt() and '45 is 25% of 180.' in txt(), txt()[:120])
        ab(1, 3); check('1 is 33.3333% of 3', '33.3333%' in txt(), txt()[:80])
        ab(5, 0); check('B = 0 shows hint, no result', pg.is_visible('#hint') and not pg.is_visible('#out') and 'cannot be 0' in pg.inner_text('#hint'))
        mode('change')
        check('mode change: defaults 80 -> 100, +25%', pg.input_value('#a') == '80' and pg.input_value('#b') == '100' and '25%' in txt() and '25% increase (+20)' in txt(), txt()[:140])
        ab(100, 80); check('100 -> 80: -20% decrease (-20)', '-20%' in txt() and '20% decrease (−20)' in txt(), txt()[:140])
        ab(50, 50); check('50 -> 50: no change', 'no change' in txt().lower(), txt()[:140])
        ab(0, 10); check('old value 0 shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        ab(10, -1); check('negative new value shows hint', pg.is_visible('#hint'))
        ab(3, 10); check('3 -> 10: 233.3333%', '233.3333%' in txt())
        mode('increase')
        check('mode increase: 20% on 500 -> 600, increase of 100', pg.input_value('#a') == '20' and '600' in txt() and 'The increase is 100' in txt(), txt()[:140])
        ab(18, 1000); check('1000 + 18% -> 1,180', '1,180' in txt())
        ab(-5, 100); check('negative percentage in increase shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        mode('decrease')
        check('mode decrease: 20% off 500 -> 400', '400' in txt() and 'The decrease is 100' in txt(), txt()[:140])
        ab(15, 1999); check('1999 - 15% -> 1,699.15, decrease 299.85', '1,699.15' in txt() and '299.85' in txt(), txt()[:140])
        ab(101, 500); check('decrease by 101% shows hint', pg.is_visible('#hint'))
        ab(100, 500); check('decrease by 100% -> 0', pg.is_visible('#out') and 'becomes 0' in txt(), txt()[:140])
        mode('of')
        ab(1234567, 8)
        check('large numbers use Indian grouping (1234567% of 8 = 98,765.36)', '98,765.36' in txt(), txt()[:100])
        ab('', 5); check('empty box hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        ab(1e13, 5); check('number above 1e12 shows hint', pg.is_visible('#hint'))
        ab(-10, 200); check('-10% of 200 -> -20', '-20' in txt())
        ab(15, 2000)
        pg.click('.sched summary')
        check('working shows 2 steps', pg.locator('.sched tbody tr').count() == 2)
        check('working step 1 has the formula with numbers', '15 ÷ 100 × 2,000' in pg.locator('.sched tbody tr').first.inner_text())
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result summary on clipboard', clip == 'What is 15% of 2,000? = 300', clip)
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget select, .widget .btn')].every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
