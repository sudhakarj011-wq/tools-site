# Browser test for the FD page. Usage: python3 tests/browser-fd.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8774', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8774/tools/fd-calculator.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        comp = lambda v: pg.click(f'#comp button[data-v="{v}"]')
        check('default: maturity ₹1,41,478, interest ₹41,478', '₹1,41,478' in txt() and '₹41,478' in txt(), txt()[:80])
        check('default compounding is Quarterly', pg.get_attribute('#comp button[data-v="4"]', 'aria-pressed') == 'true')
        check('amount words: = 1 Lakh', pg.inner_text('#amount-words') == '= 1 Lakh')
        comp(12); check('monthly -> ₹1,41,763', '₹1,41,763' in txt(), txt()[:60])
        comp(2); check('half-yearly -> ₹1,41,060', '₹1,41,060' in txt())
        comp(1); check('yearly -> ₹1,40,255', '₹1,40,255' in txt())
        check('only one compounding button pressed', pg.locator('#comp button[aria-pressed="true"]').count() == 1)
        comp(4)
        pg.fill('#amount', '500000'); pg.fill('#rate', '7.5'); pg.fill('#tenure', '3')
        check('5L, 7.5%, 3y -> ₹6,24,858', '₹6,24,858' in txt(), txt()[:60])
        pg.click('#unit button[data-v="months"]')
        check('unit to months converts 3 years -> 36', pg.input_value('#tenure') == '36')
        check('same maturity after unit switch', '₹6,24,858' in txt())
        check('tenure label says months', 'months' in pg.inner_text('#tenure-l'))
        pg.fill('#amount', '300000'); pg.fill('#rate', '6.5'); pg.fill('#tenure', '18'); comp(12)
        check('3L, 6.5%, 18 months monthly -> ₹3,30,636', '₹3,30,636' in txt(), txt()[:60])
        pg.click('#unit button[data-v="years"]')
        check('back to years: 18 months -> 2 years', pg.input_value('#tenure') == '2')
        pg.fill('#amount', '100000'); pg.fill('#rate', '7'); pg.fill('#tenure', '5'); comp(4)
        pg.eval_on_selector('#amount-r', "e=>{e.value=200000;e.dispatchEvent(new Event('input',{bubbles:true}))}")
        check('amount slider updates box and result', pg.input_value('#amount') == '200000' and '₹2,82,956' in txt(), txt()[:60])
        pg.fill('#amount', '30000000')
        check('amount above slider max still calculates', pg.is_visible('#out'))
        pg.fill('#amount', '100000')
        pg.fill('#rate', '0')
        check('0% rate: maturity = deposit', txt().count('₹1,00,000') >= 2, txt()[:70])
        pg.fill('#rate', '45')
        check('rate 45% shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        pg.fill('#rate', '')
        check('empty rate hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        pg.fill('#rate', '7'); pg.fill('#tenure', '31')
        check('31 years rejected (limit 30)', pg.is_visible('#hint'))
        pg.fill('#tenure', '30')
        check('30 years accepted', pg.is_visible('#out'))
        pg.fill('#tenure', '2.55')
        check('2.55 years rejected', pg.is_visible('#hint'))
        pg.fill('#tenure', '5')
        pg.click('.sched summary')
        rows = pg.locator('.sched tbody tr').count()
        check('schedule has 5 rows', rows == 5, str(rows))
        check('last schedule row is ₹1,41,478', '₹1,41,478' in pg.locator('.sched tbody tr').last.inner_text())
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result summary on clipboard', 'Maturity value ₹1,41,478' in clip and 'quarterly' in clip, clip)
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget .seg button, .widget .btn')].every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
