# Browser test for the income tax page. Usage: python3 tests/browser-fd.py   (needs: pip install playwright)
import subprocess, time, sys, os
from playwright.sync_api import sync_playwright
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
srv = subprocess.Popen(['python3', '-m', 'http.server', '8776', '--directory', root], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
URL = 'http://localhost:8776/tools/income-tax-calculator.html'
fails = []
def check(name, cond, extra=''):
    print(('  ok  ' if cond else '  FAIL ') + name + (f'  [{extra}]' if (extra and not cond) else ''))
    if not cond: fails.append(name)
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1280, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
        errs = []; bad = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
        pg.on('response', lambda r: bad.append(f'{r.status} {r.url}') if r.status >= 400 else None)
        pg.goto(URL); pg.wait_for_load_state('networkidle')
        txt = lambda: pg.inner_text('#out')
        seg = lambda g, v: pg.click(f'#{g} button[data-v="{v}"]')
        def setv(**kw):
            for k, v in kw.items(): pg.fill('#' + k, str(v))
        check('default 15L, 80C 1.5L: new ₹97,500, old ₹2,10,600', '₹97,500' in txt() and '₹2,10,600' in txt(), txt()[:120])
        check('default headline: New regime is better, Saves ₹1,13,100', 'New regime is better' in txt() and 'Saves ₹1,13,100' in txt())
        check('gross words: = 15 Lakh', pg.inner_text('#gross-words') == '= 15 Lakh')
        setv(gross=1200000); seg('sal', 'no')
        check('12L non-salaried with 80C 1.5L: new ₹0, old ₹1,32,600', '₹1,32,600' in txt() and 'Tax under new regime₹0' in txt().replace('\n', ''), txt()[:140])
        seg('sal', 'yes'); setv(gross=1280000)
        check('12.8L salaried: marginal relief, new tax ₹5,200', '₹5,200' in txt(), txt()[:140])
        setv(gross=1275000)
        check('12.75L salaried: new tax ₹0', 'Tax under new regime₹0' in txt().replace('\n', ''))
        setv(gross=3000000, c80c=150000, nps=50000, homeLoan=200000, other=500000)
        check('30L big deductions: Old regime is better, saves ₹31,200', 'Old regime is better' in txt() and 'Saves ₹31,200' in txt() and '₹4,44,600' in txt() and '₹4,75,800' in txt(), txt()[:160])
        setv(gross=500000, c80c=0, nps=0, homeLoan=0, other=0)
        check('5L: both zero -> Same tax', 'Same tax' in txt() and 'Both regimes' in txt(), txt()[:100])
        setv(gross=1000000); seg('age', '60to79')
        check('senior 10L: old ₹1,04,000', '₹1,04,000' in txt(), txt()[:120])
        check('only one age button pressed', pg.locator('#age button[aria-pressed="true"]').count() == 1)
        seg('age', '80plus'); setv(gross=900000)
        check('super senior 9L salaried: old ₹72,800', '₹72,800' in txt(), txt()[:120])
        seg('age', 'below60'); setv(gross=1500000, c80c=150000, nps='', homeLoan='', other='')
        check('empty deduction boxes count as zero', '₹97,500' in txt() and '₹2,10,600' in txt())
        pg.eval_on_selector('#gross-r', "e=>{e.value=2000000;e.dispatchEvent(new Event('input',{bubbles:true}))}")
        check('income slider updates box: 20L -> new ₹1,92,400, old ₹3,66,600', pg.input_value('#gross') == '2000000' and '₹1,92,400' in txt() and '₹3,66,600' in txt(), txt()[:120])
        setv(gross=5000000, c80c=0)
        check('50L accepted: new ₹10,99,800', '₹10,99,800' in txt(), txt()[:120])
        setv(gross=5000001)
        check('above 50L shows hint, no result', pg.is_visible('#hint') and not pg.is_visible('#out'))
        setv(gross=1500000, c80c=150001)
        check('80C above limit shows hint', pg.is_visible('#hint') and not pg.is_visible('#out'))
        setv(c80c=150000, nps=50001)
        check('NPS above limit shows hint', pg.is_visible('#hint'))
        setv(nps=0, gross='')
        check('empty income hides result, no hint', not pg.is_visible('#out') and not pg.is_visible('#hint'))
        setv(gross=0)
        check('zero income shows hint', pg.is_visible('#hint'))
        setv(gross=1500000, c80c=150000)
        pg.click('.sched summary')
        check('working table has 8 rows', pg.locator('.sched tbody tr').count() == 8)
        check('working table total row shows both totals', '₹97,500' in pg.locator('.sched tbody tr').last.inner_text() and '₹2,10,600' in pg.locator('.sched tbody tr').last.inner_text())
        pg.click('#copy'); pg.wait_for_timeout(200)
        clip = pg.evaluate('navigator.clipboard.readText()')
        check('Copy result summary on clipboard', 'New regime tax ₹97,500' in clip and 'Old regime tax ₹2,10,600' in clip, clip)
        check('no JS errors / failed requests', not errs and not bad, str(errs + bad))
        for w in (1440, 1280, 1024, 390):
            q = b.new_page(viewport={'width': w, 'height': 900}); q.goto(URL); q.wait_for_load_state('networkidle')
            sw = q.evaluate('document.documentElement.scrollWidth')
            check(f'no horizontal scroll at {w}px', sw <= w, str(sw))
            if w == 390:
                q.click('.sched summary')
                check('schedule opens without page overflow on mobile', q.evaluate('document.documentElement.scrollWidth') <= 390)
                ok = q.evaluate("[...document.querySelectorAll('.widget input:not([type=range]), .widget .seg button, .widget .btn')].every(e=>e.getBoundingClientRect().height>=44)")
                check('inputs and buttons are >= 44px tall on mobile', ok)
            q.close()
        b.close()
finally:
    srv.terminate()
print('\nFAILED: ' + ', '.join(fails) if fails else '\nAll browser checks passed.')
sys.exit(1 if fails else 0)
